// Platform encoding of the `planflow-ai` CLI shim (B2).
//
// The shim is the wrapper script every IDE-launched agent session gets on its
// PATH so `planflow-ai <verb>` works in ANY project. Its FORM is a per-platform
// decision made three times over — what the file is called, what is inside it,
// and whether an exec bit means anything — so it lives here as pure functions
// rather than as `process.platform` checks scattered through the writer.
//
// Why this is not cosmetic on Windows: `PATHEXT` is `.COM;.EXE;.BAT;.CMD;…`,
// so an extensionless `#!/bin/sh` file named `planflow-ai` resolves to NOTHING
// when cmd.exe or PowerShell looks up the command. The failure is silent — the
// session starts, the PATH looks right, and every CLI verb is simply missing.
//
// NFR1: the `darwin` branch reproduces `agent/cli-shim.ts`'s current output
// byte for byte (same shebang, same em dash, same `$@`, same trailing
// newline), so swapping the call site over in Phase 2 is provably a no-op.

/** The command name skills invoke — must match the CLI's own bin name. */
const SHIM_BASE_NAME = 'planflow-ai'

/** rwxr-xr-x — POSIX needs the exec bit for the shim to run directly. */
const POSIX_SHIM_EXEC_MODE = 0o755

/**
 * The shim's file name. Windows must carry a `PATHEXT` extension or the
 * command is unresolvable; `.cmd` (not `.bat`) is the modern form and is what
 * npm itself writes for its own bin shims.
 */
export function shimFileName(platform: NodeJS.Platform | string): string {
  return platform === 'win32' ? `${SHIM_BASE_NAME}.cmd` : SHIM_BASE_NAME
}

/**
 * The shim script's exact text. Pure and side-effect free so tests can assert
 * on content without touching disk — and so the version comment (which is what
 * gates regeneration in `ensureCliShim`) is comparable without a write.
 *
 * Both branches exec the bundled CLI through the SAME Electron binary the app
 * runs on, in ELECTRON_RUN_AS_NODE mode: no system Node, no npm, no PATH
 * dependency of its own.
 *
 * The Windows branch differs in three ways that all matter:
 *  - CRLF line endings — cmd.exe is only reliably tolerant of LF in simple
 *    scripts, and there is nothing to gain by betting on it.
 *  - ASCII-only comment — the file is read under the console code page, which
 *    is not UTF-8 by default; an em dash in a `rem` line is a needless risk.
 *  - `%*` forwards all arguments, the cmd.exe counterpart of `"$@"`.
 */
export function buildShimScript(
  platform: NodeJS.Platform | string,
  execPath: string,
  cliPath: string,
  version: string,
): string {
  if (platform === 'win32') {
    return [
      '@echo off',
      `rem Generated by Flow - do not edit by hand. version=${version}`,
      'setlocal',
      'set "ELECTRON_RUN_AS_NODE=1"',
      `"${execPath}" "${cliPath}" %*`,
      // cmd.exe does not propagate the child's exit code out of a script on
      // its own — without this every failed CLI verb reports success.
      'exit /b %ERRORLEVEL%',
      '',
    ].join('\r\n')
  }
  return (
    '#!/bin/sh\n' +
    `# Generated by Flow — do not edit by hand. version=${version}\n` +
    `ELECTRON_RUN_AS_NODE=1 exec "${execPath}" "${cliPath}" "$@"\n`
  )
}

/**
 * The mode to chmod the written shim to, or null where chmod is meaningless.
 * Windows has no exec bit — `fs.chmodSync` there is a no-op that reads as
 * protection, so the caller must skip it rather than call it and believe it
 * did something (the same class of lie as `chmod 0600` on credentials, B5).
 */
export function shimExecMode(platform: NodeJS.Platform | string): number | null {
  return platform === 'win32' ? null : POSIX_SHIM_EXEC_MODE
}
