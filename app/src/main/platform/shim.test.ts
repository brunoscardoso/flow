import { join } from 'path'

import { buildShimScript, shimExecMode, shimFileName } from './shim'

const EXEC_PATH = '/Applications/Flow.app/Contents/MacOS/Flow'
const BUNDLE_PATH = '/Applications/Flow.app/Contents/Resources/app/out/cli'
const VERSION = '0.1.10'

describe('shimFileName', () => {
  it('carries a PATHEXT extension on Windows and none on POSIX', () => {
    // PATHEXT is `.COM;.EXE;.BAT;.CMD;…` — an extensionless script resolves to
    // nothing there, and the session fails by losing every CLI verb silently.
    expect(shimFileName('win32')).toBe('planflow-ai.cmd')
    expect(shimFileName('darwin')).toBe('planflow-ai')
    expect(shimFileName('linux')).toBe('planflow-ai')
  })
})

describe('buildShimScript', () => {
  it('reproduces the PRE-PORT cli-shim.ts output byte for byte on darwin (NFR1)', () => {
    // The whole point of the port: cli-shim.ts writing through this function
    // must be provably a no-op on macOS. Until Phase 2 this compared against
    // cli-shim.ts's own builder — which Phase 2 then deleted in favour of this
    // one, so the comparison would have become a tautology. The property is
    // re-expressed as a PIN: the literal below is the exact text the old writer
    // produced, captured from `git show <pre-port>:app/src/main/agent/cli-shim.ts`.
    // It must never be "updated to match" — a diff here means the macOS shim
    // changed, which is the thing NFR1 forbids.
    const cliPath = join(BUNDLE_PATH, 'planflow-ai.mjs')
    expect(buildShimScript('darwin', EXEC_PATH, cliPath, VERSION)).toBe(
      '#!/bin/sh\n' +
        `# Generated by Flow — do not edit by hand. version=${VERSION}\n` +
        `ELECTRON_RUN_AS_NODE=1 exec "${EXEC_PATH}" "${cliPath}" "$@"\n`,
    )
  })

  it('writes a POSIX sh script that execs the CLI through Electron-as-Node', () => {
    const script = buildShimScript('darwin', EXEC_PATH, '/bundle/planflow-ai.mjs', VERSION)
    expect(script).toBe(
      '#!/bin/sh\n' +
        `# Generated by Flow — do not edit by hand. version=${VERSION}\n` +
        `ELECTRON_RUN_AS_NODE=1 exec "${EXEC_PATH}" "/bundle/planflow-ai.mjs" "$@"\n`,
    )
  })

  it('writes a cmd script on win32', () => {
    const script = buildShimScript(
      'win32',
      'C:\\Users\\me\\AppData\\Local\\Programs\\Flow\\Flow.exe',
      'C:\\Users\\me\\AppData\\Local\\Programs\\Flow\\resources\\app\\out\\cli\\planflow-ai.mjs',
      VERSION,
    )
    expect(script).toBe(
      [
        '@echo off',
        `rem Generated by Flow - do not edit by hand. version=${VERSION}`,
        'setlocal',
        'set "ELECTRON_RUN_AS_NODE=1"',
        '"C:\\Users\\me\\AppData\\Local\\Programs\\Flow\\Flow.exe" ' +
          '"C:\\Users\\me\\AppData\\Local\\Programs\\Flow\\resources\\app\\out\\cli\\planflow-ai.mjs" %*',
        'exit /b %ERRORLEVEL%',
        '',
      ].join('\r\n'),
    )
  })

  it('uses CRLF and stays ASCII on win32, and neither on darwin', () => {
    const windows = buildShimScript('win32', EXEC_PATH, '/cli.mjs', VERSION)
    // cmd.exe is only reliably tolerant of LF in trivial scripts, and the file
    // is read under the console code page rather than UTF-8.
    expect(windows).toContain('\r\n')
    // eslint-disable-next-line no-control-regex
    expect(/^[\x00-\x7F]*$/.test(windows)).toBe(true)

    const posix = buildShimScript('darwin', EXEC_PATH, '/cli.mjs', VERSION)
    expect(posix).not.toContain('\r')
    expect(posix).toContain('—')
  })

  it('propagates the CLI exit code on win32 (cmd.exe does not on its own)', () => {
    expect(buildShimScript('win32', EXEC_PATH, '/cli.mjs', VERSION)).toContain(
      'exit /b %ERRORLEVEL%',
    )
  })

  it('embeds the version on both platforms — regeneration is content-gated on it', () => {
    expect(buildShimScript('darwin', EXEC_PATH, '/cli.mjs', '9.9.9')).toContain('version=9.9.9')
    expect(buildShimScript('win32', EXEC_PATH, '/cli.mjs', '9.9.9')).toContain('version=9.9.9')
    // Different version → different content → the writer rewrites the file.
    expect(buildShimScript('win32', EXEC_PATH, '/cli.mjs', '9.9.9')).not.toBe(
      buildShimScript('win32', EXEC_PATH, '/cli.mjs', '9.9.8'),
    )
  })

  it('forwards all arguments in each platform’s own idiom', () => {
    expect(buildShimScript('darwin', EXEC_PATH, '/cli.mjs', VERSION)).toContain('"$@"')
    expect(buildShimScript('win32', EXEC_PATH, '/cli.mjs', VERSION)).toContain('%*')
  })
})

describe('shimExecMode', () => {
  it('is 0o755 on POSIX and null on win32', () => {
    // Null is not "no mode" — it is the caller's instruction to SKIP chmod,
    // which on Windows is a no-op that reads as protection.
    expect(shimExecMode('darwin')).toBe(0o755)
    expect(shimExecMode('linux')).toBe(0o755)
    expect(shimExecMode('win32')).toBeNull()
  })
})
