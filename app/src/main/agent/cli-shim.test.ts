// cli-shim tests — ensureCliShim's idempotent-write behavior uses a real temp
// dir (matches edit-tracker.test.ts's convention for fs-touching tests in this
// workspace). The pure script/name/mode builders moved to ../platform/shim in
// the Windows port and are asserted there; what is asserted HERE is the writer:
// which file it writes, when it rewrites, whether it chmods, and how it reports
// a shim that will not resolve.
//
// Every case passes an EXPLICIT platform rather than relying on the host, so
// both branches are covered from either OS (NFR3). Where an assertion is about
// real POSIX mode bits (which a Windows host only fakes), the case is skipped
// on a Windows host — noted inline.

import { chmodSync, existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'

import { ensureCliShim, shimResolutionProblem, withShimPath } from './cli-shim'
import { buildShimScript } from '../platform/shim'

/** Mode bits are a POSIX concept — a Windows host reports synthetic ones. */
const itPosixHost = process.platform === 'win32' ? it.skip : it

describe('ensureCliShim (posix)', () => {
  let userDataDir: string

  beforeEach(() => {
    userDataDir = mkdtempSync(join(tmpdir(), 'flow-cli-shim-'))
  })

  afterEach(() => {
    // Restore write perms before recursive removal — a leftover read-only
    // shim (from the idempotency test below) would otherwise block cleanup.
    const target = shimPath()
    if (existsSync(target)) chmodSync(target, 0o755)
    rmSync(userDataDir, { recursive: true, force: true })
  })

  function shimPath(): string {
    return join(userDataDir, 'bin', 'planflow-ai')
  }

  /** What the platform builder says the darwin shim should contain. */
  function expectedContent(bundle: string, exec: string, version: string): string {
    return buildShimScript('darwin', exec, join(bundle, 'planflow-ai.mjs'), version)
  }

  it('writes the shim script with the exec bit set and returns the shim dir', () => {
    const result = ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')

    expect(result).toBe(join(userDataDir, 'bin'))
    expect(existsSync(shimPath())).toBe(true)
    expect(readFileSync(shimPath(), 'utf8')).toBe(expectedContent('/res/cli', '/Apps/Flow', '1.0.0'))
  })

  // Host-guarded because the pin includes `join`'s own separator, exactly as
  // the pre-port writer produced it — the macOS behavior NFR1 protects.
  itPosixHost('writes the PRE-PORT bytes, at the PRE-PORT path, on darwin (NFR1)', () => {
    // The end-to-end no-op proof: not "the builder agrees with the builder",
    // but the actual file this writer puts on disk, compared against a literal
    // pinned from the pre-port `git show HEAD:app/src/main/agent/cli-shim.ts`
    // (`#!/bin/sh` + em dash + `"$@"` + trailing newline, at `<userData>/bin/
    // planflow-ai`). A diff here is a macOS behavior change, which NFR1 forbids.
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.2.3', 'darwin')

    expect(shimPath()).toBe(join(userDataDir, 'bin', 'planflow-ai'))
    expect(readFileSync(shimPath(), 'utf8')).toBe(
      '#!/bin/sh\n' +
        '# Generated by Flow — do not edit by hand. version=1.2.3\n' +
        'ELECTRON_RUN_AS_NODE=1 exec "/Apps/Flow" "/res/cli/planflow-ai.mjs" "$@"\n',
    )
  })

  itPosixHost('sets mode 0o755 on the written shim', () => {
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')
    expect(statSync(shimPath()).mode & 0o777).toBe(0o755)
  })

  it('does not rewrite the file when content is unchanged (idempotent)', () => {
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')

    // Strip write permission from the file itself — a real rewrite attempt
    // (writeFileSync, which needs FILE write access, not directory access)
    // would now fail and ensureCliShim would return null. A true skip
    // succeeds and still gets to re-assert the exec bit at the end.
    chmodSync(shimPath(), 0o444)

    const result = ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')

    expect(result).toBe(join(userDataDir, 'bin'))
    expect(readFileSync(shimPath(), 'utf8')).toBe(expectedContent('/res/cli', '/Apps/Flow', '1.0.0'))
  })

  it('rewrites the file when the version changes', () => {
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '2.0.0', 'darwin')

    expect(readFileSync(shimPath(), 'utf8')).toBe(expectedContent('/res/cli', '/Apps/Flow', '2.0.0'))
  })

  it('rewrites the file when the bundle path changes', () => {
    ensureCliShim(userDataDir, '/res/cli-old', '/Apps/Flow', '1.0.0', 'darwin')
    ensureCliShim(userDataDir, '/res/cli-new', '/Apps/Flow', '1.0.0', 'darwin')

    expect(readFileSync(shimPath(), 'utf8')).toBe(
      expectedContent('/res/cli-new', '/Apps/Flow', '1.0.0'),
    )
  })

  itPosixHost('re-asserts the exec bit even when content is unchanged', () => {
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')
    chmodSync(shimPath(), 0o644)

    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')

    expect(statSync(shimPath()).mode & 0o777).toBe(0o755)
  })

  it('creates the bin directory if missing', () => {
    expect(existsSync(join(userDataDir, 'bin'))).toBe(false)
    ensureCliShim(userDataDir, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')
    expect(existsSync(join(userDataDir, 'bin'))).toBe(true)
  })

  it('fails soft (returns null, never throws) when the target cannot be written', () => {
    // Make userDataDir a file instead of a directory — mkdirSync for the bin
    // subdir must fail (ENOTDIR), and ensureCliShim must swallow it.
    const blockedRoot = join(userDataDir, 'blocked-file')
    writeFileSync(blockedRoot, 'not a directory')

    expect(() =>
      ensureCliShim(blockedRoot, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin'),
    ).not.toThrow()
    expect(ensureCliShim(blockedRoot, '/res/cli', '/Apps/Flow', '1.0.0', 'darwin')).toBeNull()
  })
})

describe('ensureCliShim (win32)', () => {
  let userDataDir: string

  beforeEach(() => {
    userDataDir = mkdtempSync(join(tmpdir(), 'flow-cli-shim-win-'))
  })

  afterEach(() => {
    jest.restoreAllMocks()
    // Restore write perms before removal — the read-only shim left by the
    // idempotency case would otherwise block cleanup.
    if (existsSync(shimPath())) chmodSync(shimPath(), 0o755)
    rmSync(userDataDir, { recursive: true, force: true })
  })

  function shimPath(): string {
    return join(userDataDir, 'bin', 'planflow-ai.cmd')
  }

  it('writes planflow-ai.cmd — an extensionless file matches nothing in PATHEXT', () => {
    // The confirmed live defect: a Windows build wrote `<userData>\bin\planflow-ai`
    // (a `#!/bin/sh` script, no extension), so `spawn('planflow-ai')` ENOENTed
    // and every CLI verb went silently missing.
    const result = ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')

    expect(result).toBe(join(userDataDir, 'bin'))
    expect(existsSync(shimPath())).toBe(true)
    expect(existsSync(join(userDataDir, 'bin', 'planflow-ai'))).toBe(false)
  })

  it('writes the cmd script body, not the sh one', () => {
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')

    const content = readFileSync(shimPath(), 'utf8')
    expect(content).toBe(
      buildShimScript('win32', 'C:\\Flow\\Flow.exe', join('C:\\res\\cli', 'planflow-ai.mjs'), '1.0.0'),
    )
    expect(content).toContain('@echo off')
    expect(content).not.toContain('#!/bin/sh')
  })

  it('writes the exact cmd.exe bytes to disk, not just what the builder returns', () => {
    // The darwin case above pins the writer's real output against a literal;
    // the win32 case only compared the builder with itself, so a change made in
    // both places at once would have gone unnoticed. Pinned here end to end:
    // CRLF throughout, ASCII only, the `setlocal` + env line, `%*` forwarding,
    // and the exit-code line without which every failed verb reports success.
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.2.3', 'win32')

    expect(shimPath()).toBe(join(userDataDir, 'bin', 'planflow-ai.cmd'))
    // The CLI path is the one host-dependent fragment (`join`'s own separator),
    // so it is composed the way the writer composes it; every other byte here
    // is a literal.
    const cliPath = join('C:\\res\\cli', 'planflow-ai.mjs')
    expect(readFileSync(shimPath(), 'utf8')).toBe(
      '@echo off\r\n' +
        'rem Generated by Flow - do not edit by hand. version=1.2.3\r\n' +
        'setlocal\r\n' +
        'set "ELECTRON_RUN_AS_NODE=1"\r\n' +
        `"C:\\Flow\\Flow.exe" "${cliPath}" %*\r\n` +
        'exit /b %ERRORLEVEL%\r\n',
    )
  })

  itPosixHost('never chmods — the exec bit is meaningless on Windows', () => {
    // chmod on Windows is a no-op that READS as protection; calling it and
    // believing it did something is the same lie as chmod 0600 on credentials.
    // Asserted through observable state rather than a spy: the POSIX branch
    // re-asserts 0o755 on EVERY call, so a mode that survives a second call is
    // proof the chmod never happened.
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')
    chmodSync(shimPath(), 0o600)

    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')

    expect(statSync(shimPath()).mode & 0o777).toBe(0o600)
  })

  it('is idempotent — an unchanged shim is not rewritten', () => {
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')
    // Read-only the file itself: a real rewrite (writeFileSync needs FILE write
    // access) would now fail and ensureCliShim would return null.
    chmodSync(shimPath(), 0o444)

    const result = ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')

    expect(result).toBe(join(userDataDir, 'bin'))
    expect(readFileSync(shimPath(), 'utf8')).toContain('version=1.0.0')
  })

  it('rewrites when the version changes', () => {
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')
    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '2.0.0', 'win32')

    expect(readFileSync(shimPath(), 'utf8')).toContain('version=2.0.0')
  })

  it('fails soft when the target cannot be written', () => {
    const blockedRoot = join(userDataDir, 'blocked-file')
    writeFileSync(blockedRoot, 'not a directory')

    expect(() =>
      ensureCliShim(blockedRoot, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32'),
    ).not.toThrow()
    expect(
      ensureCliShim(blockedRoot, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32'),
    ).toBeNull()
  })

  it('names a shim that will not resolve instead of leaving it silent (NFR5)', () => {
    const logged = jest.spyOn(console, 'error').mockImplementation(() => {})
    // A machine whose PATHEXT was narrowed so `.CMD` is not in it — the shim is
    // written and looks fine, but Windows will never resolve the command.
    const originalPathExt = process.env['PATHEXT']
    process.env['PATHEXT'] = '.EXE'
    try {
      ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')
    } finally {
      if (originalPathExt === undefined) delete process.env['PATHEXT']
      else process.env['PATHEXT'] = originalPathExt
    }

    expect(logged).toHaveBeenCalled()
    expect(String(logged.mock.calls[0]?.[0])).toContain('will NOT resolve as a command')
  })

  it('says nothing when the shim resolves normally', () => {
    const logged = jest.spyOn(console, 'error').mockImplementation(() => {})

    ensureCliShim(userDataDir, 'C:\\res\\cli', 'C:\\Flow\\Flow.exe', '1.0.0', 'win32')

    expect(logged).not.toHaveBeenCalled()
  })
})

describe('shimResolutionProblem', () => {
  let dir: string

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'flow-shim-resolve-'))
  })

  afterEach(() => {
    rmSync(dir, { recursive: true, force: true })
  })

  it('reports a missing file on both platforms', () => {
    const missing = join(dir, 'nope.cmd')
    expect(shimResolutionProblem(missing, 'win32', '.CMD')).toContain('does not exist')
    expect(shimResolutionProblem(missing, 'darwin')).toContain('does not exist')
  })

  it('accepts a .cmd shim under a normal PATHEXT', () => {
    const file = join(dir, 'planflow-ai.cmd')
    writeFileSync(file, '@echo off\r\n')
    expect(shimResolutionProblem(file, 'win32', '.COM;.EXE;.BAT;.CMD')).toBeNull()
    // Case-insensitively, and against Windows' own default when unset.
    expect(shimResolutionProblem(file, 'win32', '.com;.exe;.bat;.cmd')).toBeNull()
    expect(shimResolutionProblem(file, 'win32', undefined)).toBeNull()
  })

  it('rejects an extension PATHEXT does not list — including none at all', () => {
    const cmd = join(dir, 'planflow-ai.cmd')
    writeFileSync(cmd, '@echo off\r\n')
    expect(shimResolutionProblem(cmd, 'win32', '.EXE')).toContain('PATHEXT')

    // The exact shape of the confirmed live defect: an extensionless file.
    const bare = join(dir, 'planflow-ai')
    writeFileSync(bare, '#!/bin/sh\n')
    const problem = shimResolutionProblem(bare, 'win32', '.COM;.EXE;.BAT;.CMD')
    expect(problem).toContain('none')
    expect(problem).toContain('PATHEXT')
  })

  itPosixHost('asks the kernel about the exec bit on POSIX', () => {
    const file = join(dir, 'planflow-ai')
    writeFileSync(file, '#!/bin/sh\n')

    chmodSync(file, 0o644)
    expect(shimResolutionProblem(file, 'darwin')).toContain('not executable')

    chmodSync(file, 0o755)
    expect(shimResolutionProblem(file, 'darwin')).toBeNull()
  })

  itPosixHost('ignores PATHEXT on POSIX — it is not a POSIX concept', () => {
    const file = join(dir, 'planflow-ai')
    writeFileSync(file, '#!/bin/sh\n')
    chmodSync(file, 0o755)
    expect(shimResolutionProblem(file, 'darwin', '.EXE')).toBeNull()
  })
})

describe('withShimPath (posix)', () => {
  it('prepends the shim dir to an existing PATH', () => {
    const env = withShimPath({ PATH: '/usr/bin:/bin', HOME: '/home/me' }, '/shim/bin', 'darwin')
    expect(env['PATH']).toBe('/shim/bin:/usr/bin:/bin')
    expect(env['HOME']).toBe('/home/me')
  })

  it('degrades to just the shim dir when PATH is missing', () => {
    const env = withShimPath({ HOME: '/home/me' }, '/shim/bin', 'darwin')
    expect(env['PATH']).toBe('/shim/bin')
  })

  it('degrades to just the shim dir when PATH is empty', () => {
    const env = withShimPath({ PATH: '' }, '/shim/bin', 'darwin')
    expect(env['PATH']).toBe('/shim/bin')
  })

  it('does not mutate the input env', () => {
    const input = { PATH: '/usr/bin' }
    withShimPath(input, '/shim/bin', 'darwin')
    expect(input).toEqual({ PATH: '/usr/bin' })
  })

  it('preserves every other var untouched', () => {
    const input = { PATH: '/usr/bin', ANTHROPIC_API_KEY: 'sk-x', CLAUDE_CONFIG_DIR: '/cfg' }
    const env = withShimPath(input, '/shim/bin', 'darwin')
    expect(env['ANTHROPIC_API_KEY']).toBe('sk-x')
    expect(env['CLAUDE_CONFIG_DIR']).toBe('/cfg')
  })

  it('does not adopt a stray `Path` key on POSIX — it is a different variable', () => {
    const env = withShimPath({ Path: '/usr/bin' }, '/shim/bin', 'darwin')
    expect(env['PATH']).toBe('/shim/bin')
    expect(env['Path']).toBe('/usr/bin')
  })
})

describe('withShimPath (win32)', () => {
  it('joins with `;`, not `:` — a `:` join fuses the whole PATH into one entry', () => {
    const env = withShimPath(
      { Path: 'C:\\Windows\\system32;C:\\Program Files\\nodejs' },
      'C:\\Users\\me\\AppData\\Roaming\\Flow\\bin',
      'win32',
    )
    expect(env['Path']).toBe(
      'C:\\Users\\me\\AppData\\Roaming\\Flow\\bin;C:\\Windows\\system32;C:\\Program Files\\nodejs',
    )
    expect(env['Path']?.split(';')).toHaveLength(3)
  })

  it('writes back to the env’s OWN key casing, never producing two PATHs', () => {
    // An object spread is case-sensitive: `{ ...env, PATH: x }` over an env
    // holding `Path` yields BOTH, and which one the child reads is then up to
    // the spawn implementation.
    const env = withShimPath({ Path: 'C:\\Windows' }, 'C:\\shim', 'win32')
    expect(Object.keys(env).filter((key) => key.toUpperCase() === 'PATH')).toEqual(['Path'])

    const upper = withShimPath({ PATH: 'C:\\Windows' }, 'C:\\shim', 'win32')
    expect(Object.keys(upper).filter((key) => key.toUpperCase() === 'PATH')).toEqual(['PATH'])
  })

  it('uses Windows’ own casing when the env has no PATH at all', () => {
    const env = withShimPath({ PATHEXT: '.COM;.EXE' }, 'C:\\shim', 'win32')
    expect(env['Path']).toBe('C:\\shim')
    expect(env['PATHEXT']).toBe('.COM;.EXE')
  })

  it('collapses an env that ALREADY carried two PATH-like keys (review F4)', () => {
    // Node's Windows process.env is case-insensitive and cannot produce this,
    // but a hand-merged env can — and overwriting one key while leaving the
    // other stale is the exact ambiguity this function exists to remove.
    const env = withShimPath(
      { Path: 'C:\\Windows', PATH: 'C:\\Old', FOO: 'bar' },
      'C:\\shim',
      'win32',
    )
    expect(Object.keys(env).filter((key) => key.toUpperCase() === 'PATH')).toHaveLength(1)
    expect(env['Path']).toBe('C:\\shim;C:\\Windows')
    expect(env['FOO']).toBe('bar')
  })

  it('never collapses keys on POSIX, where casing is significant', () => {
    // `Path` is a legitimate, DIFFERENT variable on POSIX — dropping it would
    // be data loss, so the collapse is win32-only.
    const env = withShimPath({ PATH: '/usr/bin', Path: 'unrelated' }, '/shim', 'darwin')
    expect(env['PATH']).toBe('/shim:/usr/bin')
    expect(env['Path']).toBe('unrelated')
  })

  it('does not mutate the input env', () => {
    const input = { Path: 'C:\\Windows' }
    withShimPath(input, 'C:\\shim', 'win32')
    expect(input).toEqual({ Path: 'C:\\Windows' })
  })
})
