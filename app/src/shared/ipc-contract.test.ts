const CHANNEL_NAME_PATTERN = /^[a-z][a-zA-Z]*:[a-z][a-zA-Z]*$/

describe('IPC contract channel allowlists', () => {
  it('IPC_INVOKE_CHANNELS exactly covers the IpcInvokeMap keys', () => {
    expect([...IPC_INVOKE_CHANNELS].sort()).toEqual(Object.keys(INVOKE_MAP_KEYS).sort())
  })

  it('IPC_EVENT_CHANNELS exactly covers the IpcEventMap keys', () => {
    expect([...IPC_EVENT_CHANNELS].sort()).toEqual(Object.keys(EVENT_MAP_KEYS).sort())
  })

  it('contains no duplicate channel names', () => {
    expect(new Set(IPC_INVOKE_CHANNELS).size).toBe(IPC_INVOKE_CHANNELS.length)
    expect(new Set(IPC_EVENT_CHANNELS).size).toBe(IPC_EVENT_CHANNELS.length)
  })

  it('invoke and event channels are disjoint (a channel is one or the other)', () => {
    const eventSet = new Set<string>(IPC_EVENT_CHANNELS)
    const overlap = IPC_INVOKE_CHANNELS.filter((channel) => eventSet.has(channel))
    expect(overlap).toEqual([])
  })

  it('every channel follows the <domain>:<action> naming convention', () => {
    for (const channel of [...IPC_INVOKE_CHANNELS, ...IPC_EVENT_CHANNELS]) {
      expect(channel).toMatch(CHANNEL_NAME_PATTERN)
    }
  })

  it('every channel belongs to a documented domain', () => {
    const documentedDomains = new Set([
      'threads',
      'diagnostics',
      'tasks',
      'integrations',
      'messages',
      'toolCalls',
      'subtasks',
      'credentials',
      'editor',
      'terminal',
      'attachments',
      'git',
      'flow',
      'settings',
      'blueprint',
      'brain',
      'loops',
      'project',
      'accounts',
      'review',
      'updater',
      'learn',
      'browser',
      'debug',
      'auth',
      'share',
      'knowledge',
      'workspaces',
      'plan',
    ])
    for (const channel of [...IPC_INVOKE_CHANNELS, ...IPC_EVENT_CHANNELS]) {
      const domain = channel.split(':')[0]
      expect(documentedDomains.has(domain)).toBe(true)
    }
  })
})
