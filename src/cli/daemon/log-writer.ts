/**
 * Log writer — appends formatted one-liner entries to flow/log.md.
 * Auto-creates the file with a header if it does not exist.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import type { NotificationEvent } from '../types.js';

const LOG_FILENAME = 'log.md';

const LOG_HEADER = `# Heartbeat Log

> Auto-generated by the heartbeat daemon. Do not edit manually.

`;

const LEVEL_ICONS: Record<string, string> = {
  info: '\u2705',   // checkmark
  warn: '\u23F8\uFE0F', // pause
  error: '\u274C',  // cross
};

/**
 * Format a Date as `[YYYY-MM-DD HH:MM]`.
 */
function formatTimestamp(date: Date): string {
  const y = date.getFullYear();
  const mo = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  const h = String(date.getHours()).padStart(2, '0');
  const mi = String(date.getMinutes()).padStart(2, '0');
  return `[${y}-${mo}-${d} ${h}:${mi}]`;
}

/**
 * Build a single log line from a NotificationEvent.
 *
 * Format: `[2026-03-17 14:00] <icon> <task>: <message>`
 */
export function formatLogLine(event: NotificationEvent): string {
  const ts = formatTimestamp(
    event.timestamp instanceof Date ? event.timestamp : new Date(event.timestamp),
  );
  const icon = LEVEL_ICONS[event.level] ?? '\u2139\uFE0F';
  return `${ts} ${icon} ${event.task}: ${event.message}`;
}

/**
 * Serializes appends within this process, one file at a time.
 *
 * THE APPEND IS A READ-MODIFY-WRITE and had nothing ordering it. Two overlapping
 * calls both read the same `existing`, both write their own full copy, and the
 * second one wins — so the first event is gone. Unlike `event-writer.ts` there
 * is not even a rename to fail on, so BOTH calls resolve successfully and
 * nothing is reported anywhere: the log simply has fewer lines than the events
 * that happened (#1581).
 *
 * That is the steady state, not a stress case. `flow/heartbeat.md` schedules
 * `loop-fix` and `loop-find` both `every 30 minutes`, so the daemon dispatches
 * them milliseconds apart and both immediately emit `task_started`.
 *
 * A chained promise per path is the whole fix: each append waits for the
 * previous one on the same file, so the read always sees the prior write. A
 * rejection is swallowed into the chain (never into the caller's result) so one
 * failed append cannot wedge every later one behind it.
 *
 * PER PROCESS, and honestly so. Two daemons writing one file still race; the
 * failure this answers is one daemon dispatching two tasks, which is what the
 * schedule produces every half hour.
 */
const appendChains = new Map<string, Promise<void>>();

/**
 * Append a formatted log entry to flow/log.md.
 * Creates the file with a header if it does not exist.
 */
export async function appendLog(
  flowDir: string,
  event: NotificationEvent,
): Promise<void> {
  const key = join(flowDir, LOG_FILENAME);
  const previous = appendChains.get(key) ?? Promise.resolve();
  const work = previous.then(() => appendLogUnserialized(flowDir, event));
  // The chain must not inherit this call's rejection, or one failure blocks
  // every append after it. The CALLER still sees it.
  appendChains.set(
    key,
    work.then(
      () => undefined,
      () => undefined,
    ),
  );
  return work;
}

async function appendLogUnserialized(
  flowDir: string,
  event: NotificationEvent,
): Promise<void> {
  const filePath = join(flowDir, LOG_FILENAME);
  const dir = dirname(filePath);

  await mkdir(dir, { recursive: true });

  let existing = '';
  try {
    existing = await readFile(filePath, 'utf-8');
  } catch {
    // File does not exist — will create with header
  }

  const line = formatLogLine(event);

  if (!existing) {
    await writeFile(filePath, `${LOG_HEADER}${line}\n`, 'utf-8');
  } else {
    await writeFile(filePath, `${existing.trimEnd()}\n${line}\n`, 'utf-8');
  }
}
