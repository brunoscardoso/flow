/**
 * Tests for the prose report renderer (`renderProseReport`) — section
 * presence with exact line formatting, byte-identical determinism (including
 * `derivedAt` independence), the module cap with its explicit overflow line,
 * degree/children-count fallback ordering, and the empty-graph skeleton.
 */

import { MODULE_REPORT_CAP, renderProseReport } from './prose-report.js';
import type { BlueprintGraph, BlueprintNode } from '../types.js';

// ── Shared fixtures ────────────────────────────────────────

function makeNode(overrides: Partial<BlueprintNode> & Pick<BlueprintNode, 'id' | 'kind'>): BlueprintNode {
  return {
    label: overrides.id,
    sourceFile: 'src/fixture.ts',
    ...overrides,
  };
}

function makeGraph(nodes: BlueprintNode[], edges: BlueprintGraph['edges'] = []): BlueprintGraph {
  return {
    version: 1,
    derivedAt: '2026-07-09T00:00:00.000Z',
    coverage: { filesScanned: 3, filesTotal: 4, extractorsRun: ['integrations', 'modules'], graphifyEnriched: false },
    nodes,
    edges,
  };
}

function makeFixtureGraph(): BlueprintGraph {
  return makeGraph(
    [
      makeNode({
        id: 'module:src/api',
        kind: 'module',
        label: 'api',
        sourceFile: 'src/api',
        meta: { depth: 1, fileCount: 3, degree: 5, community: 2 },
      }),
      makeNode({ id: 'module:src/lib', kind: 'module', label: 'lib', sourceFile: 'src/lib', meta: { depth: 1 } }),
      makeNode({ id: 'integration:stripe', kind: 'integration', label: 'stripe', sourceFile: 'package.json' }),
      makeNode({
        id: 'datastore:sqlite',
        kind: 'datastore',
        label: 'sqlite',
        sourceFile: 'src/db.ts',
        meta: { tables: ['users', 'orders'] },
      }),
      makeNode({
        id: 'endpoint:GET /users',
        kind: 'endpoint',
        label: 'GET /users',
        sourceFile: 'src/api/server.ts',
        meta: { method: 'GET', route: '/users' },
      }),
    ],
    [
      { source: 'module:src/api', target: 'endpoint:GET /users', relation: 'exposes' },
      { source: 'module:src/api', target: 'module:src/lib', relation: 'contains' },
    ],
  );
}

// ── Sections & formatting ──────────────────────────────────

describe('renderProseReport sections', () => {
  it('should render the header, all five sections, and exact node lines', () => {
    const report = renderProseReport(makeFixtureGraph());

    expect(report.startsWith('# Blueprint Report\n')).toBe(true);
    expect(report).toContain(
      '> Auto-generated by `planflow-ai blueprint derive` — do not edit; source of truth is `flow/brain/.structure/graph.json`.',
    );
    for (const heading of ['## Modules', '## Integrations', '## Datastores', '## Endpoints', '## Structure']) {
      expect(report).toContain(`\n${heading}\n`);
    }

    expect(report).toContain('- **api** — `src/api` · depth 1 · 3 file(s) · deg 5 · community 2');
    expect(report).toContain('- **lib** — `src/lib` · depth 1');
    expect(report).toContain('- **stripe** — `package.json`');
    expect(report).toContain('- **sqlite** — `src/db.ts` · tables: users, orders');
    expect(report).toContain('- **GET /users** — `src/api/server.ts` · GET /users');
  });

  it('should render exact Structure counts and coverage lines', () => {
    const report = renderProseReport(makeFixtureGraph());

    expect(report).toContain('- Nodes: 5 (integration 1, endpoint 1, datastore 1, module 2)');
    expect(report).toContain('- Edges: 2 (contains 1, exposes 1)');
    expect(report).toContain(
      '- Coverage: 3/4 files scanned · extractors: integrations, modules · graphify enriched: no',
    );
  });
});

// ── Determinism ────────────────────────────────────────────

describe('renderProseReport determinism', () => {
  it('should be byte-identical across renders of the same graph', () => {
    expect(renderProseReport(makeFixtureGraph())).toBe(renderProseReport(makeFixtureGraph()));
  });

  it('should not change when only derivedAt varies', () => {
    const first = makeFixtureGraph();
    const second = { ...makeFixtureGraph(), derivedAt: '2030-01-01T12:34:56.000Z' };

    expect(renderProseReport(second)).toBe(renderProseReport(first));
    expect(renderProseReport(first)).not.toContain(first.derivedAt);
  });
});

// ── Module cap & ordering ──────────────────────────────────

describe('renderProseReport module cap and ordering', () => {
  it('should cap modules at MODULE_REPORT_CAP with an explicit overflow line', () => {
    const modules = Array.from({ length: MODULE_REPORT_CAP + 2 }, (_, index) =>
      makeNode({
        id: `module:src/m-${String(index).padStart(2, '0')}`,
        kind: 'module',
        label: `m-${String(index).padStart(2, '0')}`,
        meta: { degree: 100 - index },
      }),
    );

    const report = renderProseReport(makeGraph(modules));
    const moduleLines = report.split('\n').filter((line) => line.startsWith('- **m-'));

    expect(moduleLines).toHaveLength(MODULE_REPORT_CAP);
    expect(report).toContain('…and 2 more module(s)');
    // Highest degree first; the two lowest-degree modules fell past the cap
    expect(moduleLines[0]).toContain('m-00');
    expect(report).not.toContain('- **m-16**');
  });

  it('should rank by degree, fall back to contains-children count, and tie-break by id', () => {
    const graph = makeGraph(
      [
        makeNode({ id: 'module:src/deg', kind: 'module', label: 'deg', meta: { degree: 3 } }),
        makeNode({ id: 'module:src/kids', kind: 'module', label: 'kids' }), // 2 contains-children
        makeNode({ id: 'module:src/a-tie', kind: 'module', label: 'a-tie', meta: { degree: 1 } }),
        makeNode({ id: 'module:src/b-tie', kind: 'module', label: 'b-tie', meta: { degree: 1 } }),
      ],
      [
        { source: 'module:src/kids', target: 'module:src/a-tie', relation: 'contains' },
        { source: 'module:src/kids', target: 'module:src/b-tie', relation: 'contains' },
      ],
    );

    const report = renderProseReport(graph);
    const order = report
      .split('\n')
      .filter((line) => line.startsWith('- **'))
      .map((line) => line.slice('- **'.length, line.indexOf('** —')));

    expect(order).toEqual(['deg', 'kids', 'a-tie', 'b-tie']);
  });
});

// ── Empty graph ────────────────────────────────────────────

describe('renderProseReport empty graph', () => {
  it('should render the full skeleton with explicit empty sections', () => {
    const graph: BlueprintGraph = {
      version: 1,
      derivedAt: '2026-07-09T00:00:00.000Z',
      coverage: { filesScanned: 0, filesTotal: 0, extractorsRun: [], graphifyEnriched: false },
      nodes: [],
      edges: [],
    };

    const report = renderProseReport(graph);

    for (const heading of ['## Modules', '## Integrations', '## Datastores', '## Endpoints', '## Structure']) {
      expect(report).toContain(`\n${heading}\n`);
    }
    expect(report.match(/_none derived_/g)).toHaveLength(4);
    expect(report).toContain('- Nodes: 0 (integration 0, endpoint 0, datastore 0, module 0)');
    expect(report).toContain('- Edges: 0');
    expect(report).toContain('- Coverage: 0/0 files scanned · extractors:  · graphify enriched: no');
    expect(report.endsWith('\n')).toBe(true);
  });
});
